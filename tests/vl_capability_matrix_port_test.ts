// THE POSITION MATRIX'S EXIT CONTRACT, AND WHERE THE VL PORT DIFFERS FROM THE PYTHON.
//
// `scripts/capability-matrix.vl` replaced `scripts/capability-probes/matrix.py`. Before the
// Python was deleted both were run over all 501 templates against one seed: every table and
// exit code matched, and all 28,562 generated programs matched below their header line.
// `vl_capability_matrix_test.ts` grades the port against real seeds; this suite gives it a
// STUB `vl`, because no healthy seed can be made to lose a cell or go SILENT on demand, and
// those two are the only movements the script exits non-zero on.
//
// Where the port cannot agree with the Python, pinned below rather than left as prose:
//   1. An argument error exits 2 with the usage on STDOUT (argparse wrote stderr; VL has no
//      stderr sink), and the program name is `capability-matrix.vl`.
//   2. Every other refusal (no template, an unreadable one) is one stdout line prefixed
//      `capability-matrix.vl:`, exit 1, where the Python raised (a traceback, for a
//      template it could not open).
//   3. A generated cell's first line says `generated by capability-matrix.vl`.
//
// @test-timing native

import { COMPILER, exists, nativeEnv, ROOT, VL } from "./support/tree.ts";
import { builtScript } from "./support/builtScript.ts";

const GATED = Deno.env.get("SELFHOST_NATIVE_ALIGN") === "1";
const ENABLED = GATED && exists(VL) && exists(COMPILER);
if (GATED && !ENABLED) {
  console.warn(
    "[vl-capability-matrix-port] skipped — missing vl binary or seed wasm.",
  );
}

const dec = new TextDecoder();
const TEMPLATE = "scripts/capability-probes/matrix/orerr-generic-pin.matrix.vl";

// The stub `vl`: `<cmd> <program> --compiler <seed>`. A seed named `old*` runs every cell
// and prints what its header asks for. Any other seed: `binding` and annotated `array_push`
// are check-clean invalid wasm, `argument` is a check refusal, the un-annotated
// `global_init` prints the wrong value, `local_assign` passes check and its program traps,
// `global_assign` passes check and the compiler traps building it, `closure_capture` traps
// the compiler inside `vl check`, and the rest run.
//
// The two trap texts are the host's `report` (scripts/vl-host/src/main.rs): a program trap
// exits 1 with source frames and no banner; a compiler trap exits 70 under the banner. The
// compiler one is reconstructed from that function, since no master seed traps on demand.
const PROGRAM_TRAP = [
  "Error: error while executing at wasm backtrace:",
  "    0:    0x138 - vl!float",
  "    1:    0x1fc - vl!__start__@1",
  "",
  "Caused by:",
  "    wasm trap: null reference",
  "",
  "",
  "vl source frames (innermost first):",
  "    at cell.vl:1:32  in `f`",
  "",
  "note: a null value was used where a non-null one was required.",
  "",
].join("\n");
const COMPILER_TRAP = [
  "vl: the compiler itself trapped while compiling cell.vl. This is a bug in vl, not in your program.",
  "    please report it with this file and the output below (vl 0.1.0, seed 6345507 bytes)",
  "",
  "Error: error while executing at wasm backtrace:",
  "    0: 0x1a2b3c - vl!internInlineShapeTy",
  "",
  "Caused by:",
  "    wasm trap: out of bounds array access",
  "",
  "vl source frames (innermost first):",
  "    at compiler/intern.vl:10:3  in `internInlineShapeTy`",
  "",
].join("\n");
const STUB = `#!/usr/bin/env bash
cmd=$1; f=$2; c=$4
want=$(head -1 "$f" | sed -n 's/.*Should print \\(.*\\)\\.$/\\1/p')
case "$c" in
  *old*) [ "$cmd" = run ] && echo "$want"; exit 0 ;;
esac
case "$f" in
  *_binding_*|*_array_push_ann*)
    if [ "$cmd" = run ]; then echo "[wasm] Invalid input WebAssembly code at offset 12: x" >&2; exit 1; fi
    echo "Checked 1 file, no errors."; exit 0 ;;
  *_argument_*)
    if [ "$cmd" = run ]; then echo "$f:3:1: [ERROR]: cannot pass" >&2; exit 1; fi
    echo "$f:3:1: [ERROR]: cannot pass x"; echo "Found 1 error."; exit 1 ;;
  *_global_init_un*)
    [ "$cmd" = run ] && echo "wrong answer"; exit 0 ;;
  *_local_assign_*)
    if [ "$cmd" = run ]; then printf '%s' "$PROGRAM_TRAP" >&2; exit 1; fi
    echo "Checked 1 file, no errors."; exit 0 ;;
  *_global_assign_*)
    if [ "$cmd" = run ]; then printf '%s' "$COMPILER_TRAP" >&2; exit 70; fi
    echo "Checked 1 file, no errors."; exit 0 ;;
  *_closure_capture_*)
    printf '%s' "$COMPILER_TRAP" >&2; exit 70 ;;
esac
[ "$cmd" = run ] && echo "$want"
exit 0
`;

type Out = { code: number; out: string; err: string };

const port = async (argv: string[]): Promise<Out> => {
  const { code, stdout, stderr } = await new Deno.Command(VL, {
    args: [
      "run",
      await builtScript("scripts/capability-matrix.vl", { cwd: ROOT }),
      "--",
      ...argv,
    ],
    cwd: ROOT,
    stdout: "piped",
    stderr: "piped",
    env: nativeEnv({ NO_COLOR: "1", PROGRAM_TRAP, COMPILER_TRAP }),
  }).output();
  return { code, out: dec.decode(stdout), err: dec.decode(stderr) };
};

const want = (label: string, got: Out, code: number, says: string[]) => {
  if (got.code !== code) {
    throw new Error(
      `${label}: want exit ${code}, got ${got.code}:\n${got.out}${got.err}`,
    );
  }
  for (const s of says) {
    if (!got.out.includes(s)) {
      throw new Error(
        `${label}: want stdout to contain ${
          JSON.stringify(s)
        }, got:\n${got.out}`,
      );
    }
  }
};

Deno.test({
  name:
    "capability matrix: exits 1 on runs -> not-runs and on SILENT, 0 otherwise",
  ignore: !ENABLED,
  fn: async () => {
    const dir = await Deno.makeTempDir({
      prefix: "vl_capability_matrix_port_",
    });
    try {
      const stub = `${dir}/vl`;
      await Deno.writeTextFile(stub, STUB);
      await Deno.chmod(stub, 0o755);
      const base = [TEMPLATE, "--vl", stub];

      want(
        "lost",
        await port([
          ...base,
          "--before",
          "old.wasm",
          "--after",
          "new.wasm",
          "--only",
          "argument,global_init",
        ]),
        1,
        [
          "before `old.wasm`",
          "| `argument` | annotated | RUNS | check refuses: [ERROR]: cannot pass x |",
          "| `global_init` | un-annotated | RUNS | WRONG wrong answer |",
          "runs 1 of 4 graded · 0 skipped · 0 silent · 3 other\n",
          "runs -> not-runs  3   argument/ann, argument/unann, global_init/unann\n",
          "-> silent         0\n",
          "A cell that ran and no longer runs is the one movement the gate refuses on.",
        ],
      );

      want(
        "silent",
        await port([
          ...base,
          "--compiler",
          "new.wasm",
          "--only",
          "binding,array_push",
        ]),
        1,
        [
          "| `binding` | annotated | SILENT: Invalid input WebAssembly code at offset 12: x",
          "| `array_push` | un-annotated | RUNS |",
          "runs -> not-runs  0\n",
          "-> silent         3   array_push/ann, binding/ann, binding/unann\n",
          "A SILENT cell is check-clean invalid wasm",
        ],
      );

      // A loud refusal and a wrong value are neither movement: the exit stays 0.
      want(
        "loud",
        await port([
          ...base,
          "--compiler",
          "new.wasm",
          "--only",
          "argument,global_init",
        ]),
        0,
        [
          "runs -> not-runs  0\n-> silent         0\n-> program trap   0\n",
        ],
      );

      // A trap is the compiler's only when the host says so. The program's own trap past a
      // clean check is clause 1 and exits 1; it was graded COMPILER TRAP, exit 0, from the
      // backtrace alone. The compiler's trap, in build or in check, is still COMPILER TRAP.
      want(
        "traps",
        await port([
          ...base,
          "--compiler",
          "new.wasm",
          "--only",
          "local_assign,global_assign,closure_capture",
        ]),
        1,
        [
          "| `local_assign` | annotated | TRAP (program): wasm trap: null reference |",
          "| `global_assign` | annotated | COMPILER TRAP: wasm trap: out of bounds array access |",
          "| `closure_capture` | annotated | COMPILER TRAP (check rc 70): wasm trap: out of bounds array access |",
          "runs -> not-runs  0\n-> silent         0\n",
          "-> program trap   2   local_assign/ann, local_assign/unann\n",
          "A TRAP (program) cell passed check and its built program trapped: clause 1.",
        ],
      );
      // The compiler traps alone are not a movement: exit 0, as before.
      want(
        "compiler traps",
        await port([
          ...base,
          "--compiler",
          "new.wasm",
          "--only",
          "global_assign,closure_capture",
        ]),
        0,
        ["-> program trap   0\n"],
      );

      // A cell that never ran is not lost: `new` before `old` gains, it does not regress.
      want(
        "gained",
        await port([
          ...base,
          "--before",
          "new.wasm",
          "--compiler",
          "old.wasm",
          "--only",
          "binding",
        ]),
        0,
        [
          "| `binding` | annotated | SILENT: Invalid input WebAssembly code at offset 12: x | RUNS |",
          "runs -> not-runs  0\n",
        ],
      );

      // 3: the kept programs name the script that generated them.
      const kept = `${dir}/kept`;
      want(
        "kept",
        await port([
          ...base,
          "--compiler",
          "old.wasm",
          "--only",
          "binding",
          "--out-dir",
          kept,
        ]),
        0,
        [
          `generated programs kept in ${kept}`,
        ],
      );
      const head =
        (await Deno.readTextFile(`${kept}/orerr-generic-pin_binding_ann.vl`))
          .split("\n")[0];
      if (
        !head.includes(
          "generated by capability-matrix.vl from orerr-generic-pin.matrix.vl",
        )
      ) {
        throw new Error(
          `want the cell header to name capability-matrix.vl, got ${head}`,
        );
      }
    } finally {
      await Deno.remove(dir, { recursive: true });
    }
  },
});

Deno.test({
  name:
    "capability matrix: argument errors and refusals go to stdout under the port's name",
  ignore: !ENABLED,
  fn: async () => {
    // 1.
    const bogus = await port([TEMPLATE, "--bogus"]);
    want("bogus", bogus, 2, [
      "usage: capability-matrix.vl [-h] [--compiler COMPILER]",
      "capability-matrix.vl: error: unrecognized arguments: --bogus",
    ]);
    want("missing value", await port([TEMPLATE, "--only"]), 2, [
      "capability-matrix.vl: error: argument --only: expected one argument",
    ]);
    want("help", await port(["-h"]), 0, [
      "--only ONLY          comma-separated positions",
    ]);
    // 2.
    want("no template", await port([]), 1, [
      "capability-matrix.vl: a template path is required (try --list-positions)",
    ]);
    want("unreadable", await port(["/nonexistent/x.matrix.vl"]), 1, [
      "capability-matrix.vl: cannot read /nonexistent/x.matrix.vl",
    ]);
    want("unknown position", await port([TEMPLATE, "--only", "nope"]), 1, [
      "unknown position 'nope' (try --list-positions)",
    ]);
    want("positions", await port(["--list-positions"]), 0, [
      "binding",
      "global_assign",
    ]);
  },
});
