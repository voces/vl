// ── TEST-ONLY fault injection ($VL_FAULT_INJECT) ──────────────────────────────
//
// One host-side seam, corrupted on demand, so the validate-and-render path can be
// exercised WITHOUT a live compiler bug.
//
// The path `vl check --codegen` takes when a module does not validate — emit →
// CMD_VALIDATE → `Module::validate` → `cliResult` → `cliValidateCommit(0)` →
// cli.vl's positionless `invalid-module` diagnostic → a non-zero exit — could
// previously only be reached by a program the compiler MISCOMPILES. Its test
// therefore had to name a live defect, and every fix to that defect reddened the
// test and forced someone to find another one; over one day that constant was
// re-pointed five times. Both ways out of that are bad: loosen the assertion until
// something matches, or leave a real defect unfixed to feed a test.
//
// So the corruption is injected BETWEEN emission and validation. The emitter really
// ran, the bytes really came off the `rbyte` channel, wasmtime's real validator
// really rejects them, its real message really crosses back through `cliResult`,
// and cli.vl really renders and really exits non-zero. Only the REASON the bytes
// are bad is synthetic. A test that called the renderer with a canned string, or a
// host that validated a hand-authored `.wasm` handed to it directly, would prove
// none of that wiring — see the design note in tests/vl_check_codegen_test.ts.
//
// It cannot be reached by accident: an unmistakable variable name AND a named
// value, neither of which any normal invocation sets. With the variable unset —
// which is every real run — `fault_injection` returns `None` before touching
// anything, and the seam at CMD_VALIDATE is a single `if` over that `None`.
//
// An UNRECOGNIZED value is a hard error, not a silent no-op. A typo in the value
// would otherwise leave the injecting test measuring nothing while exiting exactly
// the way an uninjected run does — the "test that passes by looking at nothing"
// failure this whole change exists to remove.

/// The recognized `$VL_FAULT_INJECT` faults. One variant, one seam: the enum exists
/// so an unknown value has something to be checked against, not as a framework.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Fault {
    /// Corrupt the FIRST function body with room for the rewrite.
    CorruptValidateBytes,
    /// Corrupt the SYNTHETIC START function's body (D1594). The variant above takes
    /// whichever body comes first, which is a user function in any program that has
    /// one - so it can never reach the start function, whose offsets had no span row
    /// at all until D1594 and printed a bare number.
    CorruptStartFnBody,
}

/// Read `$VL_FAULT_INJECT`. Unset or empty is `None` (the state every real run is
/// in); anything else unrecognized is an error naming what IS recognized.
///
/// Called ONCE, before the pump loop, so a bad value fails the invocation
/// immediately rather than at whatever file first happens to reach the seam.
fn fault_injection() -> Result<Option<Fault>> {
    let Some(raw) = std::env::var_os("VL_FAULT_INJECT") else {
        return Ok(None);
    };
    match raw.to_str() {
        None | Some("") => Ok(None),
        Some("corrupt-validate-bytes") => Ok(Some(Fault::CorruptValidateBytes)),
        Some("corrupt-start-fn-body") => Ok(Some(Fault::CorruptStartFnBody)),
        Some(other) => bail!(
            "vl: unrecognized $VL_FAULT_INJECT fault `{other}` — the values this binary \
             knows are `corrupt-validate-bytes` and `corrupt-start-fn-body`. \
             $VL_FAULT_INJECT is a TEST-ONLY hook for exercising the module-validation \
             path; unset it."
        ),
    }
}

/// Apply `fault` to `bytes` in place. One entry point, so the two seams that can inject
/// (`vl check --codegen`'s CMD_VALIDATE and `vl build`'s write-then-validate) cannot
/// disagree about what a fault name means.
fn inject_fault(fault: Fault, bytes: &mut [u8]) -> Result<()> {
    match fault {
        Fault::CorruptValidateBytes => corrupt_first_function_body(bytes),
        Fault::CorruptStartFnBody => corrupt_start_function_body(bytes),
    }
}

/// Read a u32 LEB128 at `*p`, advancing `*p`. `None` on a truncated or over-long
/// encoding, which the caller turns into a named error rather than a wrong offset.
fn leb_u32(bytes: &[u8], p: &mut usize) -> Option<u32> {
    let mut out: u32 = 0;
    let mut shift = 0;
    loop {
        let b = *bytes.get(*p)?;
        *p += 1;
        out |= ((b & 0x7f) as u32).checked_shl(shift)?;
        if b & 0x80 == 0 {
            return Some(out);
        }
        shift += 7;
        if shift > 31 {
            return None;
        }
    }
}

/// Rewrite the FIRST function body in `bytes` so the module still DECODES and fails
/// VALIDATION with a TYPE error — the same shape of rejection a real emit bug
/// produces, so the diagnostic the test asserts on is the one a real miscompile
/// renders, rather than a truncation the validator rejects at the header.
///
/// The rewrite is length-preserving, so no section or body size LEB is re-encoded:
/// the body becomes `00` (no local declaration groups), `6a` (`i32.add` against an
/// empty operand stack — a function body always starts with one, so this is a
/// guaranteed type mismatch whatever that function's signature is), `00` filler
/// (`unreachable`, which decodes), and `0b` (`end`).
///
/// EVERY precondition below is an error rather than a fallback, and that is the
/// point: this function doubles as the injecting test's proof that REAL emitted
/// bytes reached the seam. Had the host instead SUBSTITUTED a hand-authored invalid
/// blob, a broken `rbyte` channel handing back nothing would still have produced a
/// validation failure and the test would still have passed — green over a dead
/// channel. Mutating what actually arrived cannot do that.
fn corrupt_first_function_body(bytes: &mut [u8]) -> Result<()> {
    if bytes.len() < 8 || &bytes[..4] != b"\0asm" {
        bail!(
            "VL_FAULT_INJECT=corrupt-validate-bytes: the {} bytes on the `rbyte` channel are \
             not a wasm module (no `\\0asm` magic) — the emitter or the readback is broken, \
             which is a real failure and not something to inject a fault into",
            bytes.len()
        );
    }
    let total = bytes.len();
    let mut p = 8;
    while p < total {
        let id = bytes[p];
        p += 1;
        let Some(size) = leb_u32(bytes, &mut p) else {
            bail!("VL_FAULT_INJECT=corrupt-validate-bytes: bad section size LEB at {p}");
        };
        let sec_end = p + size as usize;
        if sec_end > total {
            bail!(
                "VL_FAULT_INJECT=corrupt-validate-bytes: section {id} runs past the end of \
                 the {total}-byte module"
            );
        }
        if id != 10 {
            p = sec_end;
            continue;
        }
        // The code section. Walk its bodies for the first with room for the rewrite.
        let Some(count) = leb_u32(bytes, &mut p) else {
            bail!("VL_FAULT_INJECT=corrupt-validate-bytes: bad code-section function count");
        };
        for _ in 0..count {
            let Some(body_size) = leb_u32(bytes, &mut p) else {
                bail!("VL_FAULT_INJECT=corrupt-validate-bytes: bad function body size LEB");
            };
            let (start, body_end) = (p, p + body_size as usize);
            if body_end > sec_end {
                bail!(
                    "VL_FAULT_INJECT=corrupt-validate-bytes: a function body runs past the \
                     code section"
                );
            }
            if body_size >= 3 {
                rewrite_body_invalid(bytes, start, body_end);
                return Ok(());
            }
            p = body_end;
        }
        bail!(
            "VL_FAULT_INJECT=corrupt-validate-bytes: no function body of 3+ bytes in the code \
             section — nothing to corrupt"
        );
    }
    bail!(
        "VL_FAULT_INJECT=corrupt-validate-bytes: the {total}-byte module has no code section \
         — nothing to corrupt"
    );
}

/// The length-preserving rewrite `corrupt_first_function_body` documents, applied to the
/// body occupying `[start, end)`. Callers guarantee at least 3 bytes.
fn rewrite_body_invalid(bytes: &mut [u8], start: usize, end: usize) {
    bytes[start] = 0x00; // zero local declaration groups
    bytes[start + 1] = 0x6a; // i32.add, stack empty → type mismatch
    for b in &mut bytes[(start + 2)..(end - 1)] {
        *b = 0x00; // unreachable — decodable filler
    }
    bytes[end - 1] = 0x0b; // end
}

/// Rewrite the SYNTHETIC START function's body the same way, so the failure lands where
/// a program's MODULE-SCOPE code lives (D1594).
///
/// Which body that is comes off the module itself - the start section (id 8) names a
/// function index, and subtracting the imported functions gives its position in the code
/// section - never off a guess about emission order. Every precondition is an error for
/// the reason `corrupt_first_function_body` gives: this doubles as the injecting test's
/// proof that real emitted bytes reached the seam.
fn corrupt_start_function_body(bytes: &mut [u8]) -> Result<()> {
    const F: &str = "VL_FAULT_INJECT=corrupt-start-fn-body";
    if bytes.len() < 8 || &bytes[..4] != b"\0asm" {
        bail!(
            "{F}: the {} bytes on the emitter's channel are not a wasm module (no `\\0asm` \
             magic) — the emitter or the readback is broken, which is a real failure and not \
             something to inject a fault into",
            bytes.len()
        );
    }
    let total = bytes.len();
    let (mut imports, mut start_fn, mut code) = (0u32, None, None);
    let mut p = 8;
    while p < total {
        let id = bytes[p];
        p += 1;
        let Some(size) = leb_u32(bytes, &mut p) else {
            bail!("{F}: bad section size LEB at {p}");
        };
        let sec_end = p + size as usize;
        if sec_end > total {
            bail!("{F}: section {id} runs past the end of the {total}-byte module");
        }
        match id {
            2 => imports = count_imported_funcs(bytes, p, sec_end).unwrap_or(0),
            8 => {
                let mut q = p;
                start_fn = leb_u32(bytes, &mut q);
            }
            10 => code = Some((p, sec_end)),
            _ => {}
        }
        p = sec_end;
    }
    let Some(start_fn) = start_fn else {
        bail!("{F}: the module has no start section — this program emits no top-level code");
    };
    let Some((mut p, sec_end)) = code else {
        bail!("{F}: the {total}-byte module has no code section — nothing to corrupt");
    };
    let Some(want) = start_fn.checked_sub(imports) else {
        bail!("{F}: the start function is an IMPORT (index {start_fn} of {imports}) — the \
               emitter does not do that, so the module is not the one this expects");
    };
    let Some(count) = leb_u32(bytes, &mut p) else {
        bail!("{F}: bad code-section function count");
    };
    for i in 0..count {
        let Some(body_size) = leb_u32(bytes, &mut p) else {
            bail!("{F}: bad function body size LEB");
        };
        let (body_start, body_end) = (p, p + body_size as usize);
        if body_end > sec_end {
            bail!("{F}: a function body runs past the code section");
        }
        if i == want {
            // PAST THE LOCALS VECTOR, unlike the first-body fault, which overwrites it
            // with an empty one. The start function declares locals, so zeroing that
            // vector shifts the mismatch into bytes no top-level statement covers and
            // the diagnostic falls back to naming the whole body - which is the coarser
            // half of what D1594 built. Landing on the first INSTRUCTION lands on the
            // first module-scope statement.
            let Some(code_start) = skip_locals_vec(bytes, body_start, body_end) else {
                bail!("{F}: could not decode the start function's locals vector");
            };
            if body_end < code_start + 2 {
                bail!("{F}: the start function's body has no room after its locals vector");
            }
            bytes[code_start] = 0x6a; // i32.add, stack empty → type mismatch
            for b in &mut bytes[(code_start + 1)..(body_end - 1)] {
                *b = 0x00; // unreachable — decodable filler
            }
            bytes[body_end - 1] = 0x0b; // end
            return Ok(());
        }
        p = body_end;
    }
    bail!("{F}: the start function is body {want} of {count} — the code section is too short")
}

/// The offset of a body's FIRST INSTRUCTION: past the `vec(locals)` that opens it.
///
/// Every valtype is one byte except the two general reference forms, `ref null <ht>`
/// (0x63) and `ref <ht>` (0x64), which carry a heap type - and a WasmGC module's start
/// function is full of them, so skipping the pair is not optional here.
fn skip_locals_vec(bytes: &[u8], mut p: usize, end: usize) -> Option<usize> {
    let groups = leb_u32(bytes, &mut p)?;
    for _ in 0..groups {
        leb_u32(bytes, &mut p)?; // how many locals of this type
        let t = *bytes.get(p)?;
        p += 1;
        if t == 0x63 || t == 0x64 {
            leb_u32(bytes, &mut p)?; // the heap type index
        }
        if p > end {
            return None;
        }
    }
    (p <= end).then_some(p)
}

/// How many of a module's function indices come from the IMPORT section, which is the
/// offset between a function index and its position in the code section.
fn count_imported_funcs(bytes: &[u8], mut p: usize, end: usize) -> Option<u32> {
    let n = leb_u32(bytes, &mut p)?;
    let mut funcs = 0;
    for _ in 0..n {
        for _ in 0..2 {
            let len = leb_u32(bytes, &mut p)? as usize;
            p = p.checked_add(len)?;
        }
        if p >= end {
            return None;
        }
        let kind = *bytes.get(p)?;
        p += 1;
        match kind {
            0 => {
                funcs += 1;
                leb_u32(bytes, &mut p)?;
            }
            1 => {
                p += 1; // reftype
                let flags = *bytes.get(p)?;
                p += 1;
                leb_u32(bytes, &mut p)?;
                if flags & 1 != 0 {
                    leb_u32(bytes, &mut p)?;
                }
            }
            2 => {
                let flags = *bytes.get(p)?;
                p += 1;
                leb_u32(bytes, &mut p)?;
                if flags & 1 != 0 {
                    leb_u32(bytes, &mut p)?;
                }
            }
            _ => p += 2, // global: valtype + mutability
        }
    }
    Some(funcs)
}

/// The host↔seed contract generation this binary speaks. Checked against the seed's
/// exported `hostAbi()` before the seed is trusted; a mismatch is a hard error.
///
/// Covers the guest→host string element unit, the bulk `Load`/`Store` packing over
/// the staging window, and the `CMD_*` table above. Bump in the SAME commit that
/// changes any of them, and bump `hostAbi()` in `compiler/driver.vl` with it — that
/// function's header carries the generation table and the reasoning.
///
///   1  strings are UTF-32 code points (pre-#1848)
///   2  strings are UTF-8 bytes
const HOST_ABI: i32 = 2;

/// Refuse a seed this binary cannot talk to.
///
/// WHY THIS IS AN ERROR AND NOT A WARNING. The two artifacts do not fail loudly when
/// they disagree — they produce WRONG OUTPUT AT A SUCCESSFUL EXIT CODE. #1848 flipped
/// a string's element unit from a code point to a byte while adding, removing and
/// re-typing nothing, so every export probe still succeeds and the negotiation reports
/// "compatible"; the host then reads `4 * count` bytes where the seed wrote `count`,
/// and the overshoot lands in its own leftover UTF-32 image of the last file it staged,
/// which decodes perfectly. A stale `vl test` printed readable chunks of `std/test.vl`
/// and exited 0, and a working feature was graded as broken on that output.
///
/// A seed exporting nothing here predates the stamp — which is exactly the vintage that
/// produces the bug — so absent is a mismatch, not a pass.
fn check_seed_abi(store: &mut Store<()>, inst: &Instance, source: &CompilerSource) -> Result<()> {
    let seed = inst
        .get_typed_func::<(), i32>(&mut *store, "hostAbi")
        .ok()
        .and_then(|f| f.call(&mut *store, ()).ok());
    if seed == Some(HOST_ABI) {
        return Ok(());
    }
    let seed_line = match seed {
        Some(v) => format!("the seed speaks host ABI {v}"),
        None => "the seed exports no `hostAbi` — it predates ABI versioning (ABI 1 or older)"
            .to_string(),
    };
    // Name the RESOLVED seed: the resolution order is itself the surprise. A
    // DEVELOPMENT build still prefers `./build/vl-compiler.wasm` over anything it
    // was built with; a distribution build takes no filesystem rung at all
    // (`resolve_compiler`), which is what stopped a released binary being two
    // compilers depending on where it ran (D1574).
    let where_ = match source {
        CompilerSource::Path(p) => {
            let meta = std::fs::metadata(p).ok();
            match meta.map(|m| m.len()) {
                Some(n) => format!("{p}  ({n} bytes)"),
                None => p.clone(),
            }
        }
        CompilerSource::Embedded(b) => {
            format!("embedded in this binary ({} bytes)", b.len())
        }
    };
    bail!(
        "compiler seed ABI mismatch — this `vl` binary and this seed cannot talk to each other\n\
         \n\
         \x20 this vl host speaks host ABI {HOST_ABI}\n\
         \x20 {seed_line}\n\
         \x20 seed: {where_}\n\
         \n\
         The host<->seed contract — the string element unit, the bulk Load/Store packing,\n\
         and the CMD_* command table (docs/internals/cli-design.md) — changed between\n\
         these two builds. Running them together produces WRONG OUTPUT at a successful\n\
         exit code, not a crash, so this is an error rather than a warning.\n\
         \n\
         Fix one of:\n\
         \x20 rebuild the seed for this host    scripts/refresh-compiler.sh\n\
         \x20 fetch a matching rolling seed     scripts/fetch-seed.sh\n\
         \x20 rebuild the host for this seed    (cd scripts/vl-host && cargo build --release)\n\
         \x20 point at a matching seed          --compiler <a seed that speaks ABI {HOST_ABI}>\n\
         \n\
         `vl --version` names the seed and the std this binary resolved, and which\n\
         rung each came from."
    )
}

/// Read a string payload via a bare `<prefix>Len()` / `<prefix>At(j)` accessor pair
/// (one UTF-32 code point per `At`) off an instance that is NOT the compiler — a
/// `vl test` module's `vltFailLen`/`vltFailAt`, whose exports come from `std:test`
/// and carry no bulk twin. Payloads inside the compiler go through `StrOut`, which
/// takes the bulk path when the seed offers one.
fn read_cli_str(
    store: &mut Store<()>,
    len: &TypedFunc<(), i32>,
    at: &TypedFunc<i32, i32>,
) -> Result<String> {
    let n = len.call(&mut *store, ())?;
    read_guest_str(n, |j| Ok(at.call(&mut *store, j)?))
}

/// `vl check` (and, later, every subcommand) over the command-queue pump. The host
/// performs only raw mechanism: load the compiler module, resolve the compiler
/// path + TTY colour, stream argv in, then loop servicing file reads and line
/// prints until the VL program reports CMD_DONE, and exit with its code.
fn cli_pump(args: &[String]) -> Result<()> {
    use std::io::{IsTerminal, Write};
    // Resolve the compiler module (host mechanism): --compiler / env / default.
    let mut compiler: Option<String> = None;
    let mut i = 0;
    while i < args.len() {
        if args[i] == "--compiler" {
            compiler = args.get(i + 1).cloned();
            i += 1;
        }
        i += 1;
    }
    let compiler = resolve_compiler(compiler);

    // TEST-ONLY, and `None` on every real run — see the `$VL_FAULT_INJECT` block
    // above CMD_VALIDATE. Read HERE rather than at the seam so an unrecognized
    // value fails the invocation up front instead of at whichever file first
    // validates (and never, on a run that validates nothing).
    let fault = fault_injection()?;

    // A COLLECTING collector, unlike the one-shot compile paths. The pump drives one
    // compiler instance across every file a directory walk finds, so its garbage grows
    // with the FILE COUNT; under the null collector the heap only ever grows and a walk
    // of a few dozen files dies with `wasm trap: allocation size too large`. Two copies
    // of this repo's own `compiler/` (54 files) were enough.
    let engine = gc_engine(match std::env::var("VL_PUMP_GC").ok().as_deref() {
        Some("null") => Collector::Null,
        Some("tracing") => Collector::Copying,
        Some("refcount") => Collector::DeferredReferenceCounting,
        _ => Collector::Auto,
    })?;
    let (mut store, inst) = load_compiler(&engine, &compiler)?;

    // TTY + NO_COLOR + TERM is host mechanism; the VL formatter can't probe isatty,
    // so the resolved decision rides in as a synthetic `--color=always|never`
    // argument. Same per-stream gate the help screens use (`color_ok`).
    //
    // A CALLER'S OWN `--color=` IS AN OVERRIDE, and used not to be one: the
    // synthetic argument is appended AFTER user argv and the VL parser takes the
    // last one it sees, so `vl check --color=always | less -R` resolved to
    // `never`. Resolving here — the one place that knows both the flag and the
    // isatty — is what makes `--color` mean the same thing on `run`, `check`,
    // `fmt` and `test`. An unrecognised value is a usage error rather than a
    // silent "never" (`cliParseArgs` still reads its own copy leniently; it now
    // only ever sees `always` or `never`).
    let mut choice = ColorChoice::Auto;
    for a in args {
        if let Some(v) = a.strip_prefix("--color=") {
            match ColorChoice::parse(v) {
                Some(c) => choice = c,
                None => {
                    eprintln!("vl: `{a}` — --color takes always, never, or auto");
                    std::process::exit(2);
                }
            }
        }
    }
    let color = choice.resolve(std::io::stdout().is_terminal());

    let arg_reset = inst.get_typed_func::<(), i32>(&mut store, "cliArgReset")?;
    let arg_push = inst.get_typed_func::<i32, i32>(&mut store, "cliArgPush")?;
    let arg_commit = inst.get_typed_func::<(), i32>(&mut store, "cliArgCommit")?;
    arg_reset.call(&mut store, ())?;
    for a in args {
        for ch in a.chars() {
            arg_push.call(&mut store, ch as i32)?;
        }
        arg_commit.call(&mut store, ())?;
    }
    let color_arg = if color { "--color=always" } else { "--color=never" };
    for ch in color_arg.chars() {
        arg_push.call(&mut store, ch as i32)?;
    }
    arg_commit.call(&mut store, ())?;

    let next = inst.get_typed_func::<(), i32>(&mut store, "cliNext")?;
    let cmd_path = StrOut::probe(&mut store, &inst, "cliCmdPath")?;
    let cmd_data = StrOut::probe(&mut store, &inst, "cliCmdData")?;
    let result_in = StrIn::probe(&mut store, &inst, "cliResult")?;
    let file_commit = inst.get_typed_func::<i32, i32>(&mut store, "cliFileCommit")?;
    let dir_name_push = inst.get_typed_func::<i32, i32>(&mut store, "cliDirNamePush")?;
    let dir_entry_push = inst.get_typed_func::<i32, i32>(&mut store, "cliDirEntryPush")?;
    let dir_commit = inst.get_typed_func::<i32, i32>(&mut store, "cliDirCommit")?;
    let exit_code = inst.get_typed_func::<(), i32>(&mut store, "cliExitCode")?;

    // `vl test` state: the modules the brain has handed over (CMD_TEST_STASH), then
    // what collection learned about each (CMD_TEST_COLLECT), reused by the run.
    let mut test_files: Vec<TestFile> = Vec::new();
    let mut test_regs: Vec<TestRegistry> = Vec::new();
    let mut test_engine_slot: Option<Engine> = None;

    let mut out = std::io::stdout();
    let mut err = std::io::stderr();
    loop {
        match next.call(&mut store, ())? {
            CMD_DONE => break,
            CMD_LIST_DIR => {
                // List one directory (no recursion, no skip-list, no glob — all VL
                // policy). `cliDirCommit(1)` when the path is a directory (entries
                // streamed first), `0` when it is a file or does not exist, so the
                // VL program can classify a file-vs-directory target.
                let path = cmd_path.read(&mut store)?;
                match std::fs::read_dir(&path) {
                    Ok(entries) => {
                        for entry in entries.flatten() {
                            let is_dir =
                                entry.file_type().map(|t| t.is_dir()).unwrap_or(false);
                            for ch in entry.file_name().to_string_lossy().chars() {
                                dir_name_push.call(&mut store, ch as i32)?;
                            }
                            dir_entry_push.call(&mut store, if is_dir { 1 } else { 0 })?;
                        }
                        dir_commit.call(&mut store, 1)?;
                    }
                    Err(_) => {
                        // Not a directory (a file, or missing) — no entries.
                        dir_commit.call(&mut store, 0)?;
                    }
                }
            }
            CMD_READ_FILE => {
                let path = cmd_path.read(&mut store)?;
                // The pump compiles what it is handed, so the file most recently
                // delivered is the one a trap after this point died inside — the
                // closest the HOST can get to a name the guest owns. A `std:` key
                // is EXCLUDED: it is a dependency of the file under compilation,
                // never the thing a reporter should be told to send.
                if !path.starts_with("std:") {
                    note_compiling(&path);
                }
                // A `std:` key maps to `<stdDir>/<name>.vl` (slash segments are
                // subdirectories); every other key is a filesystem path read as-is.
                // A missing file commits `found = 0` (the VL program raises its own
                // unresolvable-import / cannot-read diagnostic).
                let data = match path.strip_prefix("std:") {
                    Some(name) => read_std_module(name),
                    None => read_utf8(std::path::Path::new(&path)),
                };
                match data {
                    Some(s) => {
                        result_in.send(&mut store, &s)?;
                        file_commit.call(&mut store, 1)?;
                    }
                    None => {
                        file_commit.call(&mut store, 0)?;
                    }
                }
            }
            CMD_WRITE_FILE => {
                // Write the formatted (or fixed) contents back to disk. Path +
                // data both ride the current-command payload.
                let path = cmd_path.read(&mut store)?;
                let data = cmd_data.read(&mut store)?;
                std::fs::write(&path, data.as_bytes())
                    .map_err(|e| Error::from(e).context(format!("writing `{path}`")))?;
            }
            CMD_READ_STDIN => {
                // `… | vl fmt` — slurp stdin and commit it like a file read.
                use std::io::Read;
                let mut s = String::new();
                std::io::stdin().read_to_string(&mut s).ok();
                result_in.send(&mut store, &s)?;
                file_commit.call(&mut store, 1)?;
            }
            CMD_PRINT_OUT => {
                // Raw stdout (no added newline) — formatted source carries its own
                // trailing newline, so `vl fmt` output stays byte-exact.
                let data = cmd_data.read(&mut store)?;
                write!(out, "{data}")?;
            }
            CMD_PRINT_ERR => {
                let line = cmd_data.read(&mut store)?;
                writeln!(err, "{line}")?;
            }
            CMD_TEST_STASH => {
                // The brain just emitted a test module; keep its bytes. They come
                // back off the driver's own readback channel — the same `rbyte`
                // `Len`/`At`/`Store` triple `vl build` reads — so nothing new
                // crosses.
                let path = cmd_path.read(&mut store)?;
                let bytes = BytesOut::probe(&mut store, &inst, "rbyte")?.read(&mut store)?;
                test_files.push(TestFile { path, bytes });
            }
            CMD_TEST_COLLECT => {
                // Instantiate every stashed module in parallel (this is where the
                // Cranelift compile lands) and commit each registry back IN STASH
                // ORDER — the brain attributes names to files by commit order.
                let jobs = inst.get_typed_func::<(), i32>(&mut store, "cliTestJobsWanted")?;
                let workers = test_worker_count(jobs.call(&mut store, ())?);
                let name_push = inst.get_typed_func::<i32, i32>(&mut store, "cliTestNamePush")?;
                let name_commit =
                    inst.get_typed_func::<i32, i32>(&mut store, "cliTestNameCommit")?;
                let file_commit =
                    inst.get_typed_func::<i32, i32>(&mut store, "cliTestFileCommit")?;
                let engine_t = test_engine(&mut test_engine_slot)?;
                let trace = test_trace_on();
                let epoch = std::time::Instant::now();
                test_regs = parallel_map(test_files.len(), workers, |i| {
                    let start_us = epoch.elapsed().as_micros();
                    let reg = collect_test_file(&engine_t, &test_files[i]);
                    if trace {
                        test_trace_stamp("collect", i, start_us, epoch.elapsed().as_micros());
                    }
                    reg
                });
                for reg in &test_regs {
                    for (name, skip) in reg.names.iter().zip(reg.skips.iter()) {
                        for ch in name.chars() {
                            name_push.call(&mut store, ch as i32)?;
                        }
                        name_commit.call(&mut store, *skip)?;
                    }
                    let status = if reg.error.is_empty() { 0 } else { 1 };
                    if status != 0 {
                        result_in.send(&mut store, &reg.error)?;
                    }
                    file_commit.call(&mut store, status)?;
                }
            }
            CMD_TEST_RUN => {
                // Read the plan the brain built, group it by file (one instance per
                // file), run the files across the pool, and commit the outcomes back
                // in PLAN order so the report is deterministic.
                let jobs = inst.get_typed_func::<(), i32>(&mut store, "cliTestJobsWanted")?;
                let workers = test_worker_count(jobs.call(&mut store, ())?);
                let plan_count = inst.get_typed_func::<(), i32>(&mut store, "cliTestPlanCount")?;
                let plan_file = inst.get_typed_func::<i32, i32>(&mut store, "cliTestPlanFile")?;
                let plan_test = inst.get_typed_func::<i32, i32>(&mut store, "cliTestPlanTest")?;
                let out_push = inst.get_typed_func::<i32, i32>(&mut store, "cliTestOutPush")?;
                let res_commit =
                    inst.get_typed_func::<(i32, i32), i32>(&mut store, "cliTestResultCommit")?;
                let n = plan_count.call(&mut store, ())?;
                let mut per_file: Vec<Vec<(usize, i32)>> =
                    (0..test_regs.len()).map(|_| Vec::new()).collect();
                for k in 0..n {
                    let f = plan_file.call(&mut store, k)? as usize;
                    let t = plan_test.call(&mut store, k)?;
                    if f < per_file.len() {
                        per_file[f].push((k as usize, t));
                    }
                }
                let engine_t = test_engine(&mut test_engine_slot)?;
                let trace = test_trace_on();
                let epoch = std::time::Instant::now();
                let batches = parallel_map(per_file.len(), workers, |i| {
                    let start_us = epoch.elapsed().as_micros();
                    let batch = run_test_file(&engine_t, &test_regs[i], &per_file[i]);
                    if trace {
                        test_trace_stamp("run", i, start_us, epoch.elapsed().as_micros());
                    }
                    batch
                });
                let mut outcomes: Vec<Option<TestOutcome>> =
                    (0..n as usize).map(|_| None).collect();
                for batch in batches {
                    for (k, outcome) in batch {
                        if k < outcomes.len() {
                            outcomes[k] = Some(outcome);
                        }
                    }
                }
                for (k, slot) in outcomes.into_iter().enumerate() {
                    let outcome = slot.unwrap_or(TestOutcome {
                        status: 1,
                        message: "the runner produced no result for this test".to_string(),
                        output: String::new(),
                    });
                    if !outcome.message.is_empty() {
                        result_in.send(&mut store, &outcome.message)?;
                    }
                    for ch in outcome.output.chars() {
                        out_push.call(&mut store, ch as i32)?;
                    }
                    res_commit.call(&mut store, (k as i32, outcome.status))?;
                }
            }
            CMD_VALIDATE => {
                // `vl check --codegen` just emitted a module for the current file.
                // Run the engine's validator over it and hand the verdict back.
                //
                // This is the SAME check `vl build` runs over the file it wrote
                // (`validate_written_module`) and the one `vl run` fails on, and it
                // closes the gap that header comment used to describe: `--codegen`
                // ran the emitter and reported nothing about the module's validity,
                // so a program that could not load passed the gate that promises it
                // will lower. Nothing new crosses the boundary — the bytes come off
                // the driver's own `rbyte` readback channel, exactly as
                // CMD_TEST_STASH reads them.
                //
                // In memory, not off disk: unlike `vl build` there is no artifact
                // and no `-O` rung to cover, so the emitter's own bytes ARE what a
                // caller would run.
                //
                // The commit is probed HERE, not up front with the rest of the pump
                // exports, so a seed that predates this command — and therefore
                // never issues it — still runs under this host.
                let validate_commit =
                    inst.get_typed_func::<i32, i32>(&mut store, "cliValidateCommit")?;
                let mut bytes = BytesOut::probe(&mut store, &inst, "rbyte")?.read(&mut store)?;
                // THE SEAM. Between the emitter's bytes and the engine's verdict,
                // and nowhere else — everything below this line is the real path.
                // `fault` is `None` unless $VL_FAULT_INJECT named this fault.
                if let Some(f) = fault {
                    inject_fault(f, &mut bytes)?;
                }
                match Module::validate(&engine, &bytes) {
                    Ok(()) => {
                        validate_commit.call(&mut store, 1)?;
                    }
                    Err(e) => {
                        result_in.send(&mut store, &format!("{e}"))?;
                        validate_commit.call(&mut store, 0)?;
                    }
                }
            }
            other => bail!("vl: unknown CLI command {other} from the wasm pump"),
        }
    }
    out.flush().ok();
    err.flush().ok();
    std::process::exit(exit_code.call(&mut store, ())?);
}


// ── which module trapped ─────────────────────────────────────────────────────
//
// A wasm trap renders identically whichever module raised it, so the COMPILER's
// own crash arrives wearing the PROGRAM's error: D1500's reporter read the seed's
// `out of bounds array access` as their own index and went looking inside their
// DEFLATE decoder. Attribution is therefore RECORDED AT THE CALL BOUNDARY, where
// the instance is known, and never inferred from the message text.

/// `true` when the most recent failing wasm call went INTO the compiler module,
/// `false` when it went into the user's program. Both `from_compiler` and
/// `from_user` WRITE it, so a failure that is caught and discarded (`vl test`
/// discards one per trapping test) cannot leave a stale attribution behind for a
/// later error to inherit.
static FAULT_IN_COMPILER: AtomicBool = AtomicBool::new(false);

/// A module the emitter produced that the ENGINE refuses. `vl check` returned 0 to reach
/// the emitter at all, so an invalid module is the compiler's fault by construction: it
/// exits 70 like a compiler trap (#2483), so a caller can tell a vl BUG from a bad
/// program without parsing stderr. Set by `locate_invalid_module` (D1578).
static INVALID_MODULE: AtomicBool = AtomicBool::new(false);

/// The source file the host last handed the compiler, for the banner to name.
static COMPILING: Mutex<Option<String>> = Mutex::new(None);

/// The resolved seed's size in bytes — with the version, the pair that identifies
/// WHICH compiler crashed in a report from a checkout we cannot see.
static SEED_SIZE: AtomicUsize = AtomicUsize::new(0);

/// A crash INSIDE the compiler, as its own exit code. Distinct from 1 (the program
/// or its compilation failed) and 2 (usage) so a caller — a build script, a test
/// harness, an editor — can tell a vl BUG from a bad program without parsing
/// stderr. 70 is sysexits(3)'s `EX_SOFTWARE`, "an internal software error has been
/// detected", which is exactly the claim being made.
const EXIT_COMPILER_BUG: i32 = 70;

/// Record the file whose compile is under way, for `report`'s banner.
fn note_compiling(path: &str) {
    if let Ok(mut slot) = COMPILING.lock() {
        *slot = Some(path.to_string());
    }
}

/// Record the resolved seed's size, for `report`'s banner.
fn note_seed_size(n: usize) {
    SEED_SIZE.store(n, Ordering::Relaxed);
}

/// Tag a failed call into the COMPILER instance / into the USER program's
/// instance. Wrap the wasm call itself rather than the enclosing function: what
/// the banner claims is which MODULE was executing, and only the call site knows.
fn from_compiler<T>(r: Result<T>) -> Result<T> {
    attribute(r, true)
}

fn from_user<T>(r: Result<T>) -> Result<T> {
    attribute(r, false)
}

fn attribute<T>(r: Result<T>, compiler: bool) -> Result<T> {
    if r.is_err() {
        FAULT_IN_COMPILER.store(compiler, Ordering::Relaxed);
    }
    r
}

/// Print a failed run the way anyhow would, plus — when a wasm TRAP is anywhere in
/// the cause chain — the VL-level `note:` that says which source construct stops
/// here. Without it a trap reaches the author as an opcode name over an address
/// backtrace, with nothing naming the VL operation that refused.
///
/// A trap out of the COMPILER module gets a banner and `EXIT_COMPILER_BUG` ahead
/// of all that, because the sentence a user reads otherwise is about their own
/// code (D1500). The TRAP is required on top of the attribution flag: a link or
/// I/O failure never wears a program's error, and the flag is only as fresh as the
/// last wasm call — so requiring both leaves a stale `true` unable to blame vl for
/// a failure that never entered the compiler at all.
fn report(err: Error) -> ! {
    let trap = err.chain().find_map(|c| c.downcast_ref::<Trap>()).copied();
    let compiler_bug = trap.is_some() && FAULT_IN_COMPILER.load(Ordering::Relaxed);
    // An INVALID MODULE is the other compiler bug that exits 70, and it carries its own
    // banner inside the message (`locate_invalid_module`, D1578) — it never traps, so it
    // cannot reach the trap banner above and must not borrow its wording.
    let invalid_module = INVALID_MODULE.load(Ordering::Relaxed);
    if compiler_bug {
        let what = COMPILING.lock().ok().and_then(|p| p.clone());
        eprintln!(
            "vl: the compiler itself trapped while compiling {}. This is a bug in vl, not in your program.",
            what.as_deref().unwrap_or("your program")
        );
        eprintln!(
            "    please report it with this file and the output below (vl {}, seed {} bytes)",
            env!("CARGO_PKG_VERSION"),
            SEED_SIZE.load(Ordering::Relaxed)
        );
        eprintln!();
    }
    eprintln!("Error: {err:?}");
    if let Some(note) = trap.and_then(trap_explanation) {
        eprintln!("\nnote: {note}");
    }
    std::process::exit(if compiler_bug || invalid_module {
        EXIT_COMPILER_BUG
    } else {
        1
    });
}

fn main() {
    match real_main() {
        Ok(()) => {}
        Err(e) => report(e),
    }
}

fn real_main() -> Result<()> {
    let args: Vec<String> = std::env::args().collect();
    match args.get(1).map(String::as_str) {
        // Bare `vl` is reserved for a future REPL — see the self-discovery block.
        None => bare_usage_hint(),
        Some("--help") | Some("-h") => {
            print_overview();
            Ok(())
        }
        Some("--version") | Some("-V") => {
            print!("{}", version_report());
            Ok(())
        }
        Some("help") => match args.get(2).map(String::as_str) {
            None | Some("help") => {
                print_overview();
                Ok(())
            }
            Some(topic) if COMMANDS.contains(&topic) => {
                print_command_help(topic);
                Ok(())
            }
            Some(topic) => {
                let s = Style::stderr();
                let (c, r) = (s.cmd, s.reset);
                match suggest_command(topic) {
                    Some(fix) => eprintln!(
                        "vl: no help for `{topic}` — did you mean `{c}vl help {fix}{r}`?"
                    ),
                    None => eprintln!("vl: no help for `{topic}`"),
                }
                eprintln!("    run `{c}vl --help{r}` for the list of commands");
                std::process::exit(2);
            }
        },
        // `fmt`, `check` and `test` share the in-wasm CLI pump; the subcommand
        // rides as argv[0] so the VL program dispatches on it.
        Some(cmd @ ("fmt" | "check" | "test")) => {
            if wants_help(&args[2..], cmd, false) {
                print_command_help(cmd);
                return Ok(());
            }
            from_compiler(cli_pump(&args[1..]))
        }
        Some("run") => {
            // `stop_at_positional`: after the source file, tokens are the
            // PROGRAM's territory — `vl run p.vl --help` keeps its exit-2
            // diagnostic, which already explains `--`.
            if wants_help(&args[2..], "run", true) {
                print_command_help("run");
                return Ok(());
            }
            run_cmd(&args[2..])
        }
        Some("seed") => {
            if wants_help(&args[2..], "seed", false) {
                print_command_help("seed");
                return Ok(());
            }
            seed_cmd(&args[2..])
        }
        Some("std") => {
            if wants_help(&args[2..], "std", false) {
                print_command_help("std");
                return Ok(());
            }
            std_cmd(&args[2..])
        }
        Some("build") => {
            if wants_help(&args[2..], "build", false) {
                print_command_help("build");
                return Ok(());
            }
            build_cmd(&args)
        }
        Some(other) => unknown_command(other),
    }
}

/// `vl build` — see the header comment and `vl help build`. Takes the FULL argv
/// (flags are scanned across the whole command line, as they always were).
fn build_cmd(args: &[String]) -> Result<()> {
    let Some(input) = args.get(2).map(String::as_str) else {
        let s = Style::stderr();
        let (c, r) = (s.cmd, s.reset);
        eprintln!("vl build: missing the <file.vl> input");
        eprintln!("    usage: vl build <file.vl> [-o out.wasm]  —  see {c}vl help build{r}");
        std::process::exit(2);
    };
    let flag = |name: &str| -> Option<String> {
        args.iter()
            .position(|a| a == name)
            .and_then(|i| args.get(i + 1))
            .cloned()
    };
    let compiler = resolve_compiler(flag("--compiler"));

    let read_source = || {
        std::fs::read_to_string(input)
            .map_err(|e| Error::from(e).context(format!("reading `{input}`")))
    };
    // The compile step always runs under the null collector (one-shot batch work);
    // only the user program's own execution gets a real (DRC) collector.
    let compile_engine = gc_engine(Collector::Null)?;

    let out = flag("-o").unwrap_or_else(|| {
        input.strip_suffix(".vl").unwrap_or(input).to_string() + ".wasm"
    });
    // `--names` embeds a wasm "name" custom section (legible trap backtraces).
    let names = args.iter().any(|a| a == "--names");
    // `_located`, so a written module the engine refuses names the function it came
    // from (D1578). The instance is read only on that failure path.
    let (mut bytes, session) = compile_vl_located(
        &compile_engine,
        &compiler,
        &read_source()?,
        input,
        "compileSrc",
        names,
    )?;
    // THE SECOND SEAM (D1594). `None` on every real run — see the `$VL_FAULT_INJECT`
    // block. `vl check --codegen` renders the engine's refusal through cli.vl and this
    // path through `locate_invalid_module`, so a control that exercises only the other
    // one proves nothing about this sentence. Between the emitter's bytes and the
    // engine's verdict, and nowhere else.
    if let Some(f) = fault_injection()? {
        inject_fault(f, &mut bytes)?;
    }
    std::fs::write(&out, &bytes)?;
    // Optimize the written module in place (wasm-opt, when present). Two
    // rungs, and `-O3` WINS when both are given — it is a superset of `-O`'s
    // effect on every measured shape, so running `-O` first would only cost a
    // process spawn. `-O3` is the release profile (`RELEASE_PASSES`), not a
    // bare binaryen level.
    if args.iter().any(|a| a == "-O3") {
        optimize_in_place(&out, "-O3", RELEASE_PASSES)?;
    } else if args.iter().any(|a| a == "-O") {
        optimize_in_place(&out, "-O", OPT_PASSES)?;
    }
    let len = std::fs::metadata(&out)
        .map(|m| m.len())
        .unwrap_or(bytes.len() as u64);
    println!("wrote {out} ({len} bytes)");
    // `--wat`: also write a `.wat` text dump beside the module (wasm-dis,
    // when present). Reflects the `-O`-optimized module if both are given.
    if args.iter().any(|a| a == "--wat") {
        let wat = format!("{}.wat", out.strip_suffix(".wasm").unwrap_or(&out));
        disassemble_to_wat(&out, &wat)?;
    }
    // The written module must be a module the engine will ACCEPT — see
    // `validate_written_module`. Runs LAST so `--wat` still dumps a broken
    // module (that dump is how an emit bug gets diagnosed).
    if !args.iter().any(|a| a == "--no-validate") {
        if let Err(e) = validate_written_module(&compile_engine, &out) {
            // An OPTIMIZED artifact is binaryen's bytes, not the emitter's, so the
            // emitter's byte ranges do not describe it — keep the engine's own text
            // rather than naming a function off an offset that means something else.
            let optimized = args.iter().any(|a| a == "-O" || a == "-O3");
            return Err(locate_invalid_module(
                e,
                if optimized { None } else { session },
                input,
            ));
        }
    }
    Ok(())
}
