// ── self-discovery: help, version, usage errors ───────────────────────────────
//
// The shape follows the reference CLIs (deno, rustc, node, python3):
//
//   vl                      a SHORT hint on stderr, exit 2. Bare `vl` is reserved
//                           for a future REPL, so nothing may grow to depend on
//                           its output — but it still EXECUTES, which is all the
//                           LSP extension's spawn probe requires
//                           (lsp/src/extension.ts: `spawnSync(vl, [])`, any exit).
//   vl --help | -h | help   the overview on stdout, exit 0: synopsis, commands
//                           grouped by purpose with one-line summaries, a footer
//                           pointing at `vl help <command>`.
//   vl help <cmd>
//   vl <cmd> --help | -h    that command's help on stdout, exit 0: synopsis,
//                           flags with defaults, examples, environment variables.
//   vl --version | -V       one version line on stdout, exit 0.
//   unknown command/topic   one stderr line naming the offender + a `vl --help`
//                           pointer (and a did-you-mean when one is close), exit 2.
//
// Exit 2 is this CLI's usage-error code everywhere (`arg_error` below,
// `cliUsageErr` in compiler/cli.vl); 1 means the program or its compilation
// failed, and an unusable command line never got that far. 70 means THE COMPILER
// ITSELF crashed (`EXIT_COMPILER_BUG`, and a banner saying so): a seed trap and a
// program trap render the same, and D1500's reporter lost a session to that.
//
// COLOR IS GATED PER STREAM, at the moment of printing: ANSI reaches a stream
// only when that stream is a terminal, `NO_COLOR` is unset, and `TERM` is not
// `dumb`. There is deliberately NO global "colorize stdout" switch: `vl seed`'s
// stdout is raw wasm bytes that one stray escape byte would corrupt, so styling
// is something each printer opts into, never a wrapper every byte passes through.
// `--color=always|never|auto` overrides the ambient rule (`ColorChoice`), and is
// resolved HERE for every subcommand — including the ones whose rendering lives
// in VL, which receive the answer as a synthetic argv entry (`cli_pump`).
//
// A RUNNING PROGRAM'S OWN `print` OUTPUT IS COLORED TOO (`Palette`), under the
// same gate and Node's split: a rendered VALUE (number, boolean) is wrapped, a
// bare string is not. The escape is added by the print IMPORT, the last place
// before stdout that still knows the value's type — never inside a VL string,
// so a template hole, a serialized payload and a log file cannot capture one.

/// Whether ANSI styling may reach a stream. `stream_is_terminal` is the caller's
/// `is_terminal()` on the SPECIFIC stream being written — stdout for help,
/// stderr for usage errors — so a piped stdout with a terminal stderr colors the
/// error and not the pipe.
fn color_ok(stream_is_terminal: bool) -> bool {
    stream_is_terminal
        && std::env::var_os("NO_COLOR").is_none()
        && std::env::var_os("TERM").map_or(true, |t| t != "dumb")
}

/// The ANSI fragments one printer uses, resolved for one stream. All-empty when
/// color is off, so the format strings below need no branching.
struct Style {
    bold: &'static str,
    cmd: &'static str, // command and flag names
    dim: &'static str,
    reset: &'static str,
}

impl Style {
    fn of(stream_is_terminal: bool) -> Style {
        if color_ok(stream_is_terminal) {
            Style { bold: "\x1b[1m", cmd: "\x1b[36m", dim: "\x1b[2m", reset: "\x1b[0m" }
        } else {
            Style { bold: "", cmd: "", dim: "", reset: "" }
        }
    }
    fn stdout() -> Style {
        use std::io::IsTerminal;
        Style::of(std::io::stdout().is_terminal())
    }
    fn stderr() -> Style {
        use std::io::IsTerminal;
        Style::of(std::io::stderr().is_terminal())
    }
}

/// `--color=<when>`: the CLI's override of the ambient `color_ok` rule. `Auto` is
/// the default and means "ask `color_ok`"; the two explicit arms are an override
/// in the NO_COLOR spec's own sense — the spec asks software to honour the
/// variable "when it is not overridden by a command-line option" — so
/// `--color=always` colours a pipe with `NO_COLOR` set, which is what makes it
/// usable for `… | less -R` and for capturing a demo.
#[derive(Clone, Copy)]
enum ColorChoice {
    Always,
    Never,
    Auto,
}

impl ColorChoice {
    /// `always` / `never` / `auto`, or `None` for anything else — a caller turns
    /// that into its own usage error, because silently reading an unrecognised
    /// `--color=purple` as "never" is a flag that lies about what it did.
    fn parse(v: &str) -> Option<ColorChoice> {
        match v {
            "always" => Some(ColorChoice::Always),
            "never" => Some(ColorChoice::Never),
            "auto" => Some(ColorChoice::Auto),
            _ => None,
        }
    }
    /// The resolved yes/no for one stream.
    fn resolve(self, stream_is_terminal: bool) -> bool {
        match self {
            ColorChoice::Always => true,
            ColorChoice::Never => false,
            ColorChoice::Auto => color_ok(stream_is_terminal),
        }
    }
}

/// The ANSI a `print` of a RENDERED VALUE is wrapped in, resolved once per process
/// and handed to `instantiate_program`. Empty strings when colour is off, so the
/// print imports pay one `is_empty()` and no allocation.
///
/// THE PALETTE IS NODE'S, MEASURED RATHER THAN INVENTED. `util.inspect.styles` on
/// node v24.11.1 is `{number: 'yellow', bigint: 'yellow', boolean: 'yellow',
/// null: 'bold', undefined: 'grey', string: 'green', …}` and `util.inspect.colors`
/// gives yellow as `[33, 39]` — the OPEN/CLOSE pair, not `[0m`, so a colour reset
/// never cancels a bold the surrounding shell set. Confirmed on a pty:
/// `console.log(5)` emits `ESC[33m5ESC[39m`, `console.log(true)` the same, and
/// `console.log("s")` emits `s` with no escape at all. That last one is the whole
/// split this stage implements: VL's string prints go through
/// `__print_char__`/`__print_str_flush__`, which never touch this type.
///
/// `null: 'bold'` is recorded for Stage C2; VL has no null print sink today (the
/// per-type import family is i32/i64/f32/f64/bool/char), so there is nothing here
/// to colour yet.
#[derive(Clone, Copy)]
struct Palette {
    /// `(open, close)` around a rendered number or boolean.
    value: (&'static str, &'static str),
}

impl Palette {
    /// No escape can ever be produced. The value every capture sink gets: `vl
    /// test` (whose captured output is pushed CHARACTER BY CHARACTER into a VL
    /// string for the reporter — an escape there would be an escape inside a VL
    /// string value, which the ruling forbids outright) and `vl run --batch`
    /// (whose `.out` files are compared byte-for-byte by the corpus).
    const OFF: Palette = Palette { value: ("", "") };

    fn of(on: bool) -> Palette {
        if on {
            Palette {
                value: ("\x1b[33m", "\x1b[39m"),
            }
        } else {
            Palette::OFF
        }
    }

    /// Hand one RENDERED VALUE to `sink`, wrapped when colour is on. Only the
    /// numeric and boolean print imports call this; the string family does not,
    /// so a bare string prints raw on a terminal exactly as it does in a pipe.
    fn emit(self, sink: &impl Fn(&str), rendered: &str) {
        let (open, close) = self.value;
        if open.is_empty() {
            sink(rendered);
        } else {
            sink(&format!("{open}{rendered}{close}"));
        }
    }
}

/// The subcommands `vl` knows, for existence checks and did-you-mean.
const COMMANDS: &[&str] = &["run", "build", "check", "fmt", "test", "seed", "std", "help"];

/// The flags of `cmd` that TAKE A VALUE, so a help scan never mistakes a flag's
/// value for `--help` (`vl run -e --help` compiles the snippet `--help`).
fn value_flags(cmd: &str) -> &'static [&'static str] {
    match cmd {
        "run" => &["-e", "--compiler", "--out-dir"],
        "build" => &["-o", "--compiler"],
        "check" => &["--compiler", "--severity", "--exclude"],
        "fmt" => &["--compiler"],
        "test" => &["--compiler", "-t", "--jobs", "--exclude"],
        "seed" => &["--out", "--compiler"],
        "std" => &["--dump"],
        _ => &[],
    }
}

/// Whether `rest` (the args after the subcommand) asks for help: a `-h`/`--help`
/// that is not a value-taking flag's value and sits before any literal `--`
/// (everything after `--` belongs to the program). `stop_at_positional` is set
/// for `vl run`, where tokens after the source file are the PROGRAM's — there
/// `vl run p.vl --help` keeps its existing exit-2 diagnostic, which already
/// explains how to pass `--help` through.
fn wants_help(rest: &[String], cmd: &str, stop_at_positional: bool) -> bool {
    let values = value_flags(cmd);
    let mut i = 0;
    while i < rest.len() {
        let a = rest[i].as_str();
        if a == "--" {
            return false;
        }
        if a == "-h" || a == "--help" {
            return true;
        }
        if values.contains(&a) {
            i += 1; // skip the flag's value
        } else if stop_at_positional && !a.starts_with('-') {
            return false;
        }
        i += 1;
    }
    false
}

/// `vl --version` / `-V`. The host ABI generation rides along because a
/// host/seed mismatch is the version question users actually hit (see
/// `check_seed_abi`).
fn version_line() -> String {
    format!("vl {} (host ABI {HOST_ABI})", env!("CARGO_PKG_VERSION"))
}

/// `vl --version` in full: the version line, the commit this binary was built
/// from, and — the reason the command grew past one line — WHICH SEED AND WHICH
/// std it is about to use, named by origin.
///
/// The two questions it answers are the two consumer defects: a binary that
/// paired a current seed with a stale checkout's `std/` (D1573), and a binary
/// that was two different compilers depending on the current directory (D1574).
/// Neither was visible from the outside; both are one command now.
fn version_report() -> String {
    let mut out = version_line();
    out.push('\n');
    out += &format!("commit:  {}\n", env!("VL_BUILD_COMMIT"));

    let (seed, seed_origin) = resolve_compiler_with_origin(None);
    let (seed_where, seed_bytes) = match &seed {
        CompilerSource::Path(p) => (p.clone(), std::fs::metadata(p).map(|m| m.len()).ok()),
        CompilerSource::Embedded(b) => ("embedded".to_string(), Some(b.len() as u64)),
    };
    out += &match seed_bytes {
        Some(n) => format!("seed:    {seed_where} ({n} bytes) — {}\n", seed_origin.label()),
        None => format!("seed:    {seed_where} (unreadable) — {}\n", seed_origin.label()),
    };

    let (std_src, std_origin) = std_source();
    let modules = resolved_std_modules();
    let hash = std_hash(modules.iter().map(|(n, s)| (n.as_str(), s.as_slice())));
    let where_ = match std_src {
        StdSource::Dir(d) => d.display().to_string(),
        StdSource::Embedded => "embedded".to_string(),
    };
    out += &format!(
        "std:     {where_} ({} modules, {hash}) — {}\n",
        modules.len(),
        std_origin.label()
    );
    // The embedded digest rides along ONLY when it is not the one above: the whole
    // point is to make a development override visible AS a difference.
    let embedded = embedded_std_hash();
    if *std_origin != StdOrigin::Embedded && embedded != hash {
        out += &format!(
            "         embedded std is {embedded} ({} modules) — this binary is running \
             a std it was not built with\n",
            std_embedded::STD_MODULES.len()
        );
    }
    out
}

/// Bare `vl`: a SHORT stderr hint — the most common commands and where the full
/// list lives — never the overview (bare `vl` is reserved for a future REPL, and
/// a rich bare-`vl` screen is exactly what tooling would start scraping).
fn bare_usage_hint() -> ! {
    let s = Style::stderr();
    let (c, d, r) = (s.cmd, s.dim, s.reset);
    eprintln!("vl: no command given {d}(a bare `vl` is reserved for a future REPL){r}");
    eprintln!();
    eprintln!("  {c}vl run{r} <file.vl>    compile and run a program");
    eprintln!("  {c}vl check{r} [path]     typecheck and report diagnostics");
    eprintln!("  {c}vl --help{r}           list every command");
    std::process::exit(2);
}

/// Levenshtein distance, for the did-you-mean below. Six candidate commands and
/// short strings: the O(len²) table is at most a few dozen cells.
fn edit_distance(a: &str, b: &str) -> usize {
    let a: Vec<char> = a.chars().collect();
    let b: Vec<char> = b.chars().collect();
    let mut prev: Vec<usize> = (0..=b.len()).collect();
    for (i, ca) in a.iter().enumerate() {
        let mut cur = vec![i + 1];
        for (j, cb) in b.iter().enumerate() {
            let cost = usize::from(ca != cb);
            cur.push((prev[j] + cost).min(prev[j + 1] + 1).min(cur[j] + 1));
        }
        prev = cur;
    }
    prev[b.len()]
}

/// The closest known command within edit distance 2 — `vl chekc` suggests
/// `check`. Deliberately not a fuzzier matcher: two edits catches the typo
/// shapes people make (transposition, one wrong/missing letter) and nothing a
/// suggestion would mislead on.
fn suggest_command(bad: &str) -> Option<&'static str> {
    COMMANDS
        .iter()
        .map(|c| (edit_distance(bad, c), *c))
        .filter(|(d, _)| *d <= 2)
        .min_by_key(|(d, _)| *d)
        .map(|(_, c)| c)
}

/// Unknown subcommand: one line naming the offender, a did-you-mean when one is
/// close, and the `vl --help` pointer. Stderr, exit 2.
fn unknown_command(bad: &str) -> ! {
    let s = Style::stderr();
    let (c, r) = (s.cmd, s.reset);
    match suggest_command(bad) {
        Some(fix) => eprintln!("vl: unknown command `{bad}` — did you mean `{c}{fix}{r}`?"),
        None => eprintln!("vl: unknown command `{bad}`"),
    }
    eprintln!("    run `{c}vl --help{r}` for the list of commands");
    std::process::exit(2);
}

