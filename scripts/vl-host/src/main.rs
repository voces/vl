// The native `vl` tool — a single binary with deno-style subcommands:
//
//   vl build <in.vl> -o <out.wasm>   compile a file to a wasm module, then VALIDATE it
//   vl check <in.vl>                 typecheck; print diagnostics (`--codegen` emits + VALIDATES)
//   vl run   <in.vl> [args...]       compile in-memory, then instantiate + run
//                                    (`--` ends host parsing; the rest is the program's)
//   vl fmt   [path] [-w|--check]     format source (stdout / write / CI gate); stdin when no path
//   vl test  [path] [-t <name>]      discover `*.test.vl`, run them in parallel, report
//   vl seed  [--out|--path]          write the resolved compiler seed (raw wasm) to stdout/file
//   vl help  [<command>]             the overview / one command's help (also --help, -h)
//
// A bare `vl` is RESERVED for a future REPL: it prints a short hint to stderr and
// exits 2, so no tooling grows to depend on bare-`vl` output before the REPL lands.
//
// The wasm validator lives in wasmtime, and the compiler is a VL program inside the
// guest with no engine of its own — so telling a valid module from an invalid one is
// always the host's job. `build` validates the file it wrote, `run` validates before
// it translates, and `check --codegen` now hands its bytes over too (CMD_VALIDATE),
// so all three report module validity. (Before that it ran the emitter and never let
// the bytes leave the guest, which made a clean `--codegen` compatible with a module
// that could not load — the check-clean-invalid-wasm class. An older version of this
// header claimed `check` did "emit-validate" when it did not; it does now, by the
// mechanism named here.) `--no-validate` opts out on both commands.
//
// This is a THIN host adapter: all compiler logic (lex/parse/typecheck/emit) lives
// in the self-hosted compiler wasm (`build/vl-compiler.wasm`, self-compiled from
// the VL-written compiler — see scripts/refresh-compiler.sh / fetch-seed.sh). The
// Rust side only does argv, file I/O, stdout, and the wasmtime embedding — it never
// parses or types VL. Future subcommands (fmt, test, …) follow the same shape: the
// brains land in the wasm, the adapter stays an I/O shim.
//
// SEED AND std RESOLUTION — first hit wins (D1573, D1574; the table also lives in
// `vl --help` and docs/internals/cli-design.md):
//
//   seed   --compiler <path> · $VL_COMPILER_WASM · a DEVELOPMENT tree's
//          build/vl-compiler.wasm · the copy embedded in this binary
//   std    $VL_STD · a DEVELOPMENT tree's std/ · the copy embedded in this binary
//
// A DISTRIBUTION build (`--features embed-seed`, which bakes the seed in via
// build.rs) takes NEITHER development rung and never consults the current
// directory: it pairs only with the copies inside it, so a pin is one file. An
// explicit override still wins, and a distribution binary announces it on stderr,
// because the failure this replaces was silent — a released `vl` pairing a current
// seed with a stale checkout's `std/`, and picking up whatever `./build/` held.
